function foodValues(r: FoodRow): string {
  return `(${u(r.id)}, ${q(r.dataset)}, ${n(r.fdc_id)}, ${q(r.external_id)}, ${q(r.name)}, ${n(r.calories)}, ${n(r.protein)}, ${n(r.carbs)}, ${n(r.fat)}, ${n(r.fiber)}, ${q(r.status_reason)})`
}

function fingerprintSql(): string {
  return `  (SELECT count(*) || ':' || md5(coalesce(string_agg(concat_ws(':', id, food_item_id, quantity_g, calories, protein_g, carbs_g, fat_g, fiber_g), ',' ORDER BY id), ''))
     FROM public.food_entries) AS e,
  (SELECT count(*) || ':' || md5(coalesce(string_agg(concat_ws(':', id, total_calories, total_protein_g, total_carbs_g, total_fat_g), ',' ORDER BY id), ''))
     FROM public.daily_summaries) AS d,
  (SELECT count(*) || ':' || md5(coalesce(string_agg(id || entries::text, ',' ORDER BY id), ''))
     FROM public.saved_entries) AS s,
  (SELECT count(*) || ':' || md5(coalesce(string_agg(concat_ws(':', id, user_id, normalized_name, food_item_id, origin), ',' ORDER BY id), ''))
     FROM public.user_food_memory) AS m`
}
const searchProbeSql = (probes: string[]) =>
  `SELECT coalesce(jsonb_agg(jsonb_build_array(p.ord, s.id, s.match_kind, s.score) ORDER BY p.ord, s.o), '[]'::jsonb)
    FROM unnest(ARRAY[${probes.map(q).join(', ')}]) WITH ORDINALITY AS p(q, ord)
    CROSS JOIN LATERAL (SELECT x.*, row_number() OVER () AS o FROM public.search_foods(p.q, 10) x) s`
// the resolver's fts candidate query WITH the guard (macroResolver.ts): same probes, all verified matches, by id
const ftsProbeSql = (probes: string[], guarded: boolean) =>
  `SELECT coalesce(jsonb_agg(jsonb_build_array(p.ord, t.id) ORDER BY p.ord, t.id), '[]'::jsonb)
    FROM unnest(ARRAY[${probes.map(q).join(', ')}]) WITH ORDINALITY AS p(q, ord)
    JOIN public.food_items t ON to_tsvector('english'::regconfig, t.name) @@ websearch_to_tsquery('english'::regconfig, p.q)
   WHERE t.status = 'verified' AND t.calories_per_100g IS NOT NULL${guarded ? ' AND t.normalized_name IS NOT NULL' : ''}`

