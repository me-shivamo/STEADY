const hdr = (file: string, sha: string) => `-- ${file} — GENERATED by scripts/import-usda.ts; inputs_sha256 ${sha}; do not edit`

function counts<T>(xs: T[], key: (x: T) => string): Record<string, number> {
  const m: Record<string, number> = {}
  for (const x of xs) { const k = key(x); m[k] = (m[k] ?? 0) + 1 }
  return Object.fromEntries(Object.entries(m).sort((a, b2) => (a[0] < b2[0] ? -1 : a[0] > b2[0] ? 1 : 0)))
}
const byDataset = (rows: Array<{ dataset: Dataset }>): Record<Dataset, number> =>
  Object.fromEntries(DATASETS.map((d) => [d, rows.filter((r) => r.dataset === d).length])) as Record<Dataset, number>

// ── manifest (what the migrations' self-checks assert, and the review doc prints) ──
interface SourceCounts { usda_foundation: number; usda_sr: number; usda_fndds: number }
const sourceCounts = (rows: PortionRow[]): SourceCounts => ({
  usda_foundation: rows.filter((p) => p.dataset === 'foundation').length,
  usda_sr: rows.filter((p) => p.dataset === 'sr').length,
  usda_fndds: rows.filter((p) => p.dataset === 'fndds').length,
})
export function manifestOf(plan: Plan, sha: string) {
  const portionSources = sourceCounts(plan.portions)
  return {
    inputs_sha256: sha,
    releases: Object.fromEntries(DATASETS.map((d) => [d, { release: plan.pins[d].release, file: plan.pins[d].file, sha256: plan.pins[d].sha256 }])),
    subset: { ...byDataset(plan.subset.kept.map((f) => ({ dataset: f.dataset }))), total: plan.subset.kept.length },
    excluded: counts(plan.subset.excluded, (e) => `${e.food.dataset}: ${e.reason}`),
    energy_ids: counts(plan.subset.kept, (f) => `${f.dataset}:${f.nutrients.energyId}`),
    invalid: { ...byDataset(plan.invalid.map((x) => ({ dataset: x.food.dataset }))), total: plan.invalid.length },
    skipped_verified_fdc: { ...byDataset(plan.skippedVerified.map((f) => ({ dataset: f.dataset }))), total: plan.skippedVerified.length },
    duplicates: { ...byDataset(plan.duplicates.map((d) => ({ dataset: d.food.dataset }))), total: plan.duplicates.length },
    foods: { ...byDataset(plan.foods), total: plan.foods.length },
    flags: counts(plan.foods.flatMap((f) => f.status_reason.split(' ').slice(4)), (x) => x),
    portions: {
      ...portionSources, total: plan.portions.length,
      defaults: plan.portions.filter((p) => p.is_default).length,
      on_imported_foods: plan.portions.filter((p) => p.target === 'import').length,
      replay: {
        ...sourceCounts(plan.portions.filter((p) => p.target === 'import')),
        defaults: plan.portions.filter((p) => p.target === 'import' && p.is_default).length,
      },
      on_verified_rows: plan.portions.filter((p) => p.target === 'verified').length,
      by_unit: counts(plan.portions, (p) => p.unit),
      report: plan.portionReport,
    },
    category_map: { total: plan.map.length, by_category: counts(plan.map, (m) => m.category) },
  }
}

