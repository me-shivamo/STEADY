function renderAliases(plan: Plan): string {
  const esc = (s: string) => (/[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s)
  const rows = proposedKeys(plan)
  return ['food_item_id,fdc_id,dataset,name,proposed_key,words,flag',
    ...rows.map((r) => [r.food_item_id, String(r.fdc_id), r.dataset, esc(r.name), esc(r.proposed_key), String(r.words), r.flag].join(','))].join('\n') + '\n'
}

export function renderAll(bulk: Bulk): Record<string, string> {
  const plan = buildPlan(bulk)
  const sha = inputsSha256()
  const man = manifestOf(plan, sha)
  // every inserted name normalizes to a non-empty phrase (search_usda_local can find it)
  const empty = plan.foods.filter((f) => normText(f.name) === '')
  if (empty.length) throw new Error(`rows whose name normalizes to nothing: ${empty.map((f) => f.fdc_id).join(', ')}`)
  return {
    [OUT.m055]: render055(plan, sha, man),
    [OUT.m056]: render056(plan, sha, man),
    [OUT.r055]: renderDown055(plan, sha),
    [OUT.r056]: renderDown056(plan, sha),
    [OUT.check056]: renderCheck056(sha),
    [OUT.doc]: renderDoc(plan, sha, man),
    [OUT.manifest]: JSON.stringify(man, null, 1) + '\n',
    [OUT.aliases]: renderAliases(plan),
  }
}
