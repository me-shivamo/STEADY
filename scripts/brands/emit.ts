export function inputsSha256(): string {
  const h = createHash('sha256')
  for (const f of INPUT_FILES) { h.update(f + '\0'); h.update(readFileSync(join(REPO, f))); h.update('\0') }
  return h.digest('hex')
}

export interface Paths { migration: string; down: string; reviewList: string; manifest: string; number: string | null }
export function pathsFor(number: string | null): Paths {
  if (number !== null && !/^\d{3}$/.test(number)) throw new Error(`--number must be three digits, got ${number}`)
  return {
    migration: number ? `supabase/migrations/${number}_brand_items.sql` : 'supabase/pending/brand_items.sql',
    down: number ? `supabase/rollback/${number}_brand_items_down.sql` : 'supabase/rollback/brand_items_down.sql',
    reviewList: 'scripts/brands/out/review_list.csv',
    manifest: 'scripts/brands/out/manifest.json',
    number,
  }
}

// ── SQL literals ──────────────────────────────────────────────────────────────────────────────────────────
function q(s: string): string {
  if (s.includes('\0')) throw new Error('NUL in text')
  return `'${s.replace(/'/g, "''")}'`
}
const qn = (s: string | null): string => (s === null ? 'NULL' : q(s))
const num = (s: string | null): string => {
  if (s === null) return 'NULL'
  if (!/^\d+(?:\.\d{1,3})?$/.test(s)) throw new Error(`not a numeric literal: ${s}`)
  return s
}
const bool = (b: boolean | null): string => (b === null ? 'NULL' : b ? 'true' : 'false')
const arr = (xs: string[]): string => {
  for (const x of xs) if (!/^[a-z0-9_]+$/.test(x)) throw new Error(`bad code ${x}`)
  return xs.length ? `ARRAY[${xs.map(q).join(',')}]::text[]` : `'{}'::text[]`
}

