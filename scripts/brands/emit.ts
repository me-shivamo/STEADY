function chunked<T>(xs: readonly T[], n: number): T[][] {
  const out: T[][] = []
  for (let i = 0; i < xs.length; i += n) out.push(xs.slice(i, i + n))
  return out
}

// ── Impact of each decision (for the founder): counts under every simple option ──────────────────────────
export interface Totals { verified: number; held: number; unserved: number; omitted: number; default_size: number; default_region: number }
export function totals(b: Build): Totals {
  const t: Totals = { verified: 0, held: 0, unserved: 0, omitted: b.omitted.length, default_size: 0, default_region: 0 }
  for (const it of b.items) {
    t[it.status]++
    if (it.is_default_size) t.default_size++
    if (it.is_default_region && (it.brand_key === 'mcdonalds' || it.brand_key === 'behrouz')) t.default_region++
  }
  return t
}
function withDecided(ds: Decisions, id: DecisionId, value: unknown): Decisions {
  return { ...ds, [id]: { ...ds[id], status: 'DECIDED', chosen: value } } as Decisions
}
export function impacts(raw: readonly RawRow[], ds: Decisions): Record<string, Array<{ option: unknown; totals: Totals }>> {
  const out: Record<string, Array<{ option: unknown; totals: Totals }>> = {}
  for (const id of DECISION_IDS) {
    if (RECORDED_ONLY.includes(id)) continue
    const opts = ds[id].options.filter((o) => !(typeof o === 'string' && o.includes(' ')) && !JSON.stringify(o).includes('<'))
    if (opts.length === 0) continue
    out[id] = opts.map((option) => ({ option, totals: totals(buildItems(raw, withDecided(ds, id, option))) }))
  }
  return out
}

// ── Manifest ──────────────────────────────────────────────────────────────────────────────────────────────
export function servedUnsigned(b: Build, f: DecisionsFile): string[] {
  return countsByBrand(b).filter((c) => c.verified > 0 && !f.signoffs[c.brand_slug]).map((c) => c.brand_slug)
}
function reasonCounts(b: Build): Record<string, number> {
  const m = new Map<string, number>()
  for (const it of [...b.items, ...b.omitted]) {
    for (const part of (it.status_reason ?? '').split('; ').filter(Boolean)) {
      const k = part.replace(/ \(.*\)$/, '')
      m.set(k, (m.get(k) ?? 0) + 1)
    }
  }
  return Object.fromEntries([...m.entries()].sort((a, z) => (a[0] < z[0] ? -1 : 1)))
}

export function renderManifest(b: Build, f: DecisionsFile, raw: readonly RawRow[], sha: string, p: Paths): string {
  const ds = f.decisions
  const m = {
    generated_by: GENERATOR,
    inputs_sha256: sha,
    migration: p.migration,
    rollback: p.down,
    migration_number: p.number,
    csv_rows: raw.length,
    totals: totals(b),
    default_size_groups: b.defaults,
    reasons: reasonCounts(b),
    by_brand: countsByBrand(b),
    decisions: Object.fromEntries(DECISION_IDS.map((id) => [id, {
      status: ds[id].status,
      source: ds[id].source ?? null,
      effective: effective(ds, id),
      recorded_only: RECORDED_ONLY.includes(id),
      releases_held_rows_only_when_decided: RELEASING.includes(id),
    }])),
    pending_founder: pendingIds(ds),
    impact_if_decided: impacts(raw, ds),
    signoffs: f.signoffs,
    served_brands_without_signoff: servedUnsigned(b, f),
  }
  return JSON.stringify(m, null, 2) + '\n'
}

// ── Review list: every row that is not served (held, unserved, omitted) ─────────────────────────────────────
const csvField = (s: string): string => `"${s.replace(/"/g, '""')}"`
export function renderReviewList(b: Build): string {
  const head = ['status', 'status_reason', 'brand_slug', 'source_row', 'brand', 'item', 'variant_or_size', 'serving_desc', 'serving_g', 'serving_ml',
    'kcal', 'protein_g', 'carbs_g', 'fat_g', 'sugar_g', 'atwater_ok', 'gate_codes', 'qa_severity', 'qa_flag', 'source_url', 'page_or_section', 'id']
  const rows = [...b.items.filter((it) => it.status !== 'verified').map((it) => ({ it, status: it.status as string })), ...b.omitted.map((it) => ({ it, status: 'omitted' }))]
    .sort((a, z) => (a.it.brand_slug === z.it.brand_slug ? a.it.source_row - z.it.source_row : a.it.brand_slug < z.it.brand_slug ? -1 : 1))
  const lines = [head.join(',')]
  for (const { it, status } of rows) {
    const r = it.raw
    lines.push([status, it.status_reason ?? '', it.brand_slug, String(it.source_row), it.brand, it.item, r.variant_or_size, r.serving_desc, r.serving_g, r.serving_ml,
      r.kcal, r.protein_g, r.carbs_g, r.fat_g, r.sugar_g, it.atwater_ok === null ? '' : String(it.atwater_ok), it.gate_codes.join(' '), it.qa_severity, r.qa_flag,
      it.source_url, r.page_or_section, it.id].map(csvField).join(','))
  }
  return lines.join('\n') + '\n'
}

