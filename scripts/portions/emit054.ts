// Generates supabase/migrations/054_portion_units.sql and
// supabase/rollback/054_portion_units_down.sql from the reviewed seed data.
//
//   npx tsx scripts/portions/emit054.ts           write both files
//   npx tsx scripts/portions/emit054.ts --check   regenerate in memory; exit 1 if either file differs
//
// Inputs (all in the repo; their sha256 goes in the header): scripts/portions/data/*.csv, 053's
// `_portion053` block, portionText.ts (classifyMeasure decides the fold-in rows), this file and lib.ts.
// Output is deterministic: rows are sorted by their UUIDv5 id, numbers are printed canonically, and
// nothing reads the clock. Spec: .claude/plans/v1.2-phase5-7-spec.md (b) 054, (e), (k).

