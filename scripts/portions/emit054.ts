const MIGRATION = join(REPO, 'supabase', 'migrations', '054_portion_units.sql')
const ROLLBACK = join(REPO, 'supabase', 'rollback', '054_portion_units_down.sql')

// ── SQL literals ──────────────────────────────────────────────────────────────
const q = (s: string | null | undefined): string => (s === null || s === undefined ? 'NULL' : `'${s.replace(/'/g, "''")}'`)
const n = (x: number | null | undefined): string => {
  if (x === null || x === undefined) return 'NULL'
  if (!Number.isFinite(x)) throw new Error(`not a finite number: ${x}`)
  return String(Number(x))   // canonical: 38.5, 0.66, 4518
}
const b = (x: boolean): string => (x ? 'true' : 'false')
const u = (x: string | null): string => (x === null ? 'NULL' : `${q(x)}::uuid`)
const list = (xs: readonly string[]) => xs.map((x) => q(x)).join(',')

const UNIT_LIST = list([...UNITS, 'ml'])
const PARSED_UNIT_LIST = list(UNITS)
const ENTRY_UNIT_LIST = list([...UNITS, 'g', 'ml'])
const SOURCES = list(['founder', 'weighed', 'research', 'legacy_hint', 'mapping', 'food_items_portions', 'usda_foundation', 'usda_sr', 'usda_fndds'])
const PORTION_SOURCES = list(['stated', 'memory', 'user_calibration', 'food', 'category', 'volume', 'serving_default', 'ai', 'label', 'edit_rescale', 'rule', 'legacy'])
const MEMORY_ORIGINS = list(['correction', 'calibration', 'manual', 'label'])

function inputsSha256(): string {
  const h = createHash('sha256')
  for (const f of INPUT_FILES) {
    h.update(f + '\0')
    h.update(readFileSync(join(REPO, f)))
    h.update('\0')
  }
  return h.digest('hex')
}

function chunked<T>(xs: T[], size: number): T[][] {
  const out: T[][] = []
  for (let i = 0; i < xs.length; i += size) out.push(xs.slice(i, i + size))
  return out
}

function rowValues(r: SeedRow): string {
  return `(${u(r.id)}, ${u(r.food_item_id)}, ${n(r.fdc_id)}, ${q(r.category)}, ${q(r.unit)}, ${q(r.size)}, ${n(r.grams)}, ${n(r.ml)}, ` +
    `${q(r.context)}, ${q(r.region)}, ${b(r.is_default)}, ${b(r.is_unit_default)}, ${q(r.source)}, ${q(r.grade)}, ${n(r.confidence)}, ` +
    `${q(r.source_ref)}, ${q(r.source_text)}, ${q(r.approved_by)}, ${q(r.status)}, ${q(r.evidence)})`
}

