# ── scripts/eval/search-check.sql: 058's lines ───────────────────────────────────────────────────────
def search_check(text, plan):
    """Rewrite the cases block for 058: ids of rows 058 quarantines -> their successor; the phrases in targets.csv's
    search_check column -> rule and row (a phrase that is a 058 key expects that key's row). Idempotent; 053's own
    rewrite (recalc.py) touches only its phrases and its ids, so both generators' `check` stay green."""
    start = text.index('WITH cases(q, want, rule) AS (VALUES')
    end = text.index('\nSELECT c.rule', start)
    block = text[start:end]
    succ = plan['successor']
    block = re.sub(r"'([0-9a-f-]{36})'::uuid", lambda m: f"'{succ.get(m.group(1), m.group(1))}'::uuid", block)
    by_key = {r['key']: r['id'] for r in plan['new_rows']}
    for d in plan['derivations']:
        for part in filter(None, (d.get('search_check') or '').split(';')):
            qq, rule = part.split('=')
            rule, _, at = rule.partition('@')        # 'upma rava=top1@rava upma': that key's row is expected
            rid = by_key.get(at or qq, d.get('canonical_row'))
            if rid is None:
                raise SystemExit(f'search_check {qq!r}: not a 058 key and its variant has no canonical row')
            pat = re.compile(r"\(" + re.escape(q(qq)) + r",(\s*)(?:'[0-9a-f-]{36}'::uuid|NULL),\s*'[a-z0-9]+'\)")
            if not pat.search(block):
                raise SystemExit(f'search-check.sql has no case line for {qq!r}; add it by hand once')
            block = pat.sub(lambda m: f"({q(qq)},{m.group(1)}'{rid}'::uuid, '{rule}')", block)
    out = text[:start] + block + text[end:]
    # the PASS criteria in the header follow the case counts of the block (top1 keeps the judge's 2-miss allowance), so
    # a passing run can be read against them; 053's rewrite touches the cases block only, so its `check` stays green
    cnt = {r: len(re.findall(r",\s*'" + r + r"'\)", block)) for r in ('alias', 'top1', 'top5')}
    subs = [(r"^-- PASS \(with all of 052's founder defaults seeded, [^\n]*\):$",
             "-- PASS (with all of 052's founder defaults seeded, 053's and 058's):"),
            (r"^--   alias  \d+/\d+  ", f"--   alias  {cnt['alias']}/{cnt['alias']}  "),
            (r"^--   top1   >= \d+/\d+  ", f"--   top1   >= {cnt['top1'] - 2}/{cnt['top1']}  "),
            (r"^--   top5   \d+/\d+   ", f"--   top5   {cnt['top5']}/{cnt['top5']}   ")]
    for pat_, rep in subs:
        out, k = re.subn(pat_, rep, out, count=1, flags=re.M)
        if k != 1:
            raise SystemExit(f'search-check.sql: PASS header line {pat_!r} not found')
    return out


