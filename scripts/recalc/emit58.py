def num(x):
    """A numeric literal: never exponent notation, no trailing zeros (150, 2.3, 115.46)."""
    if x is None:
        return 'NULL'
    d = Decimal(str(x))
    return format(d.normalize(), 'f') if d != 0 else '0'


def vals_sql(v):
    return ', '.join(num(v[k]) for k in ('kcal', 'protein', 'carbs', 'fat', 'fiber'))


def phrase_variants(key):
    """What users type for a key: the key, title case, shouted with punctuation and doubled spaces, and padded upper
    case. Each must normalize (macroResolver.ts normalizeName; its SQL twin NORM_SQL) to the key itself."""
    return [key, key.title(), key.upper().replace(' ', '  ') + '!', '  ' + key.upper() + '  ']


def phrases(plan):
    out = []
    for r in plan['new_rows']:
        for p in phrase_variants(r['key']):
            out.append((p, r['key'], r['id']))
    return sorted(out)


def portion_label(r):
    return R_fmt(r['portions'])


def R_fmt(port):
    return ', '.join(f"{p['description']} = {p['gramWeight']:g} g" for p in port) if port else 'no portion'


def new_kind(r):
    return 'successor' if r['predecessor'] else ('key copy' if r['method'] == 'key_copy' else 'new key')


